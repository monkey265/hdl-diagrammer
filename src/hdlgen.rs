//! Write the diagram back out as a top-level VHDL entity or SystemVerilog module: the top pins
//! become ports, nets become signals, blocks become instances with their connected ports.
//! Generics, port types of sub-blocks and anything the diagram never held are not reproduced.
use crate::model::{Diagram, Direction, Instance};
use std::collections::{BTreeSet, HashMap};
use std::fmt::Write;

/// Every real block in order: groups are flattened, interface bundles unfolded.
fn flat(d: &Diagram) -> Vec<Instance> {
    fn walk(list: &[Instance], out: &mut Vec<Instance>) {
        for i in list {
            if i.is_group {
                walk(&i.children, out);
            } else {
                out.push(i.clone());
            }
        }
    }
    let mut d = d.clone();
    crate::interface::expand_all(&mut d, 20);
    let mut out = Vec::new();
    walk(&d.instances, &mut out);
    out
}

/// `u_gen[0]` / `u(1)` (copies of a generate loop) are not legal instance names: `u_gen_0`, `u_1`.
fn ident(name: &str) -> String {
    let s: String = name
        .chars()
        .map(|c| {
            if c.is_alphanumeric() || c == '_' {
                c
            } else {
                '_'
            }
        })
        .collect();
    s.trim_end_matches('_').to_string()
}

fn connected(sig: &str) -> bool {
    !sig.is_empty()
}

/// Names of plain signals used by blocks that are not top-level ports (these need a declaration).
fn internal_signals(blocks: &[Instance], d: &Diagram) -> BTreeSet<String> {
    let ports: BTreeSet<&str> = d.top_level_pins.iter().map(|p| p.signal.as_str()).collect();
    blocks
        .iter()
        .flat_map(|i| i.ports.iter().map(|p| p.signal.as_str()))
        .filter(|s| {
            connected(s)
                && !s.eq_ignore_ascii_case("open")
                && !ports.contains(s)
                && s.chars()
                    .next()
                    .is_some_and(|c| c.is_alphabetic() || c == '_')
                && s.chars().all(|c| c.is_alphanumeric() || c == '_')
        })
        .map(String::from)
        .collect()
}

pub fn to_vhdl(d: &Diagram, signals: &HashMap<String, String>, top: &str) -> String {
    let blocks = flat(d);
    let mut s = String::new();
    let _ = writeln!(
        s,
        "-- generated by hdl-diagrammer; generics are not preserved"
    );
    let _ = writeln!(s, "library ieee;\nuse ieee.std_logic_1164.all;\n");
    let _ = writeln!(s, "entity {top} is");
    if !d.top_level_pins.is_empty() {
        let _ = writeln!(s, "  port (");
        let n = d.top_level_pins.len();
        for (k, p) in d.top_level_pins.iter().enumerate() {
            let dir = match p.direction {
                Direction::In => "in",
                Direction::Out => "out",
                Direction::InOut => "inout",
            };
            let ty = signals.get(&p.name).map_or("std_logic", String::as_str);
            let _ = writeln!(
                s,
                "    {} : {dir} {ty}{}",
                p.name,
                if k + 1 < n { ";" } else { "" }
            );
        }
        let _ = writeln!(s, "  );");
    }
    let _ = writeln!(s, "end entity {top};\n\narchitecture generated of {top} is");
    for n in internal_signals(&blocks, d) {
        let ty = signals.get(&n).map_or("std_logic", String::as_str);
        let _ = writeln!(s, "  signal {n} : {ty};");
    }
    let _ = writeln!(s, "begin");
    for i in &blocks {
        let _ = writeln!(s, "  {} : entity work.{}", ident(&i.name), i.entity);
        let maps: Vec<String> = i
            .ports
            .iter()
            .filter(|p| connected(&p.signal))
            .map(|p| format!("      {} => {}", p.name, p.signal))
            .collect();
        if !maps.is_empty() {
            let _ = writeln!(s, "    port map (\n{}\n    );", maps.join(",\n"));
        } else {
            let _ = writeln!(s, "    ;");
        }
    }
    let _ = writeln!(s, "end architecture generated;");
    s
}

pub fn to_sv(d: &Diagram, signals: &HashMap<String, String>, top: &str) -> String {
    let blocks = flat(d);
    let mut s = String::new();
    let _ = writeln!(
        s,
        "// generated by hdl-diagrammer; parameters are not preserved"
    );
    let _ = writeln!(s, "module {top} (");
    let n = d.top_level_pins.len();
    for (k, p) in d.top_level_pins.iter().enumerate() {
        let dir = match p.direction {
            Direction::In => "input",
            Direction::Out => "output",
            Direction::InOut => "inout",
        };
        let _ = writeln!(
            s,
            "  {dir} logic {}{}",
            p.name,
            if k + 1 < n { "," } else { "" }
        );
    }
    let _ = writeln!(s, ");");
    for name in internal_signals(&blocks, d) {
        let _ = signals; // SystemVerilog widths are not tracked: declared as single bits
        let _ = writeln!(s, "  logic {name};");
    }
    for i in &blocks {
        let maps: Vec<String> = i
            .ports
            .iter()
            .filter(|p| connected(&p.signal))
            .map(|p| format!("    .{}({})", p.name, p.signal))
            .collect();
        let _ = writeln!(
            s,
            "  {} {} (\n{}\n  );",
            i.entity,
            ident(&i.name),
            maps.join(",\n")
        );
    }
    let _ = writeln!(s, "endmodule");
    s
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::net::design_to_diagram;
    use crate::parser::{sv::parse_sv, vhdl::parse_vhdl};

    type Shape = Vec<(String, String, Vec<(String, String)>)>;

    fn shape(d: &crate::parser::Design) -> Shape {
        d.instances
            .iter()
            .map(|i| {
                let mut p: Vec<_> = i
                    .ports
                    .iter()
                    .filter(|p| !p.signal.is_empty())
                    .map(|p| (p.name.clone(), p.signal.clone()))
                    .collect();
                p.sort();
                (ident(&i.name), i.entity.clone(), p)
            })
            .collect()
    }

    #[test]
    fn vhdl_export_parses_back_to_the_same_design() {
        for src in [
            include_str!("../tests/fixtures/RC4_sync_top.vhd"),
            include_str!("../tests/fixtures/radio_top.vhd"),
        ] {
            let orig = parse_vhdl(src);
            let diagram = design_to_diagram(&orig, 20);
            let out = to_vhdl(&diagram, &orig.signals, &orig.top_name);
            let back = parse_vhdl(&out);
            assert_eq!(back.top_name, orig.top_name);
            assert_eq!(back.top_ports.len(), orig.top_ports.len());
            assert_eq!(shape(&back), shape(&orig));
            assert!(back.warnings.is_empty(), "{:?}", back.warnings);
        }
    }

    #[test]
    fn sv_export_parses_back_to_the_same_connections() {
        let orig = parse_sv(include_str!("../tests/fixtures/sample_top.sv"));
        let diagram = design_to_diagram(&orig, 20);
        let out = to_sv(&diagram, &orig.signals, &orig.top_name);
        let back = parse_sv(&out);
        assert_eq!(back.top_name, orig.top_name);
        assert_eq!(shape(&back), shape(&orig));
    }
}
